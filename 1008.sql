-- banana 고객이 주문한 제품의 이름을 검색하시오.
SELECT 제품.제품명 FROM 제품, 주문 WHERE 주문.주문고객='banana' AND 제품.제품번호=주문.주문제품;

-- 감자만두를 주문한 고객의 이름을 검색하시오.
SELECT DISTINCT 고객.고객이름 FROM 고객, 주문, 제품 WHERE 주문.주문고객=고객.고객아이디 AND 주문.주문제품=제품.제품번호 AND 제품.제품명='감자만두';

-- 고객, 주문 테이블 조인
-- 데이터베이스에서 나이가 30세 이상인 고객이 주문한 제품의 번호와 주문일자를 검색하시오.
SELECT 주문.주문제품, 주문.주문일자 FROM 고객, 주문 WHERE 고객.나이 >= 30 AND 고객.고객아이디=주문.주문고객;

-- 나이가 25세 이상인 고객이 주문한 제품의 번호, 주문일자, 고객이름을 검색하시오.
SELECT 주문.주문제품, 주문.주문일자, 고객.고객이름
    FROM 주문, 고객 
    WHERE 고객.나이>=25 AND 고객.고객아이디=주문.주문고객
    ORDER BY 주문제품 ASC;
    
-- 고명석 고객이 주문한 제품의 제품명을 검색하시오.
SELECT 제품.제품명 FROM 고객, 제품, 주문 WHERE 고객.고객이름='고명석' AND 제품.제품번호=주문.주문제품 AND 주문.주문고객=고객.고객아이디;

-- 정소화 고객이 주문한 제품의 제품명을 검색하시오. (단, 제품명이 한 번 씩만 나오게 하시오.)
SELECT DISTINCT 제품.제품명 FROM 고객, 제품, 주문 WHERE 고객.고객이름='정소화' AND 제품.제품번호=주문.주문제품 AND 주문.주문고객=고객.고객아이디;

-- 내부 조인(Inner Join)
-- 고객이 주문한 제품의 번호와 주문일자를 검색하시오. (단, 내부 조인으로 작성)
SELECT 고객.고객이름, 주문.주문제품, 주문.주문일자
    FROM 고객
    INNER JOIN 주문
    ON 고객.고객아이디=주문.주문고객;
    
-- 고객의 성이 정 또는 김 또는 고인 고객이 주문한 제품의 번호와 주문일자를 검색하시오. (단, 내부 조인으로 작성)
SELECT 고객.고객이름, 주문.주문제품, 주문.주문일자 FROM 고객 INNER JOIN 주문 ON 고객.고객아이디=주문.주문고객 WHERE 고객이름 LIKE '정%' OR 고객이름 LIKE '김%' OR 고객이름 LIKE '고%';

-- 외부조인(Outer Join)
-- 주문하지 않은 고객도 포함해서 고객이름, 주문제품, 주문일자를 검색하시오.
SELECT 고객이름, 주문제품, 주문일자 FROM 고객 LEFT OUTER JOIN 주문 ON 고객아이디=주문고객; -- 왼쪽 외부조인
SELECT 고객이름, 주문제품, 주문일자 FROM 주문 RIGHT OUTER JOIN 고객 ON 고객아이디=주문고객; -- 오른쪽 외부조인

