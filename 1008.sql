-- 그룹별 검색
-- 주문 테이블에서 주문고객별 주문한 제품의 총주문수량을 검색하시오.
SELECT 주문고객, SUM(수량) AS 총주문수량
    FROM 주문
    GROUP BY 주문고객;

-- 주문 테이블에서 각 주문고객이 주문한 제품의 총주문수량을 주문제품별로 검색하시오.
SELECT 주문제품, 주문고객, SUM(수량) AS 총주문수량
    FROM 주문
    GROUP BY 주문제품, 주문고객;

-- 위 SQL문에 정렬을 추가하시오.
SELECT 주문제품, 주문고객, SUM(수량) AS 총주문수량
    FROM 주문
    GROUP BY 주문제품, 주문고객
    ORDER BY 주문제품 ASC;

