-- 주문, 제품 테이블 조인(부모 테이블의 외래키(FK)와 자식 테이블의 기본키(PK) 속성을 사용)
-- 자연 조인
-- 주문 테이블과 제품 테이블을 조인 검색 하시오.
SELECT * FROM 주문, 제품 WHERE 주문.주문제품=제품.제품번호;

-- 주문 테이블과 제품 테이블을 조인 검색 하시오. (주문번호, 주문고객, 제품명, 단가, 제조업체만 출력)
SELECT 주문번호, 주문고객, 제품명, 단가, 제조업체
    FROM 주문, 제품
    WHERE 주문.주문제품=제품.제품번호;
    
-- 주문 테이블과 고객, 제품 테이블을 조인 검색 하시오. (주문번호, 주문고객, 고객이름, 제품명, 단가, 수량, 제조업체만 출력)
SELECT 주문.주문번호, 주문.주문고객, 고객.고객이름, 제품.제품명, 제품.단가, 주문.수량, 제품.제조업체
    FROM 주문, 고객, 제품
    WHERE 주문.주문제품=제품.제품번호 AND 주문.주문고객=고객.고객아이디;

-- 주문 테이블의 결과에 제품명이 함께 출력되도록 검색하시오.
SELECT * FROM 주문; -- 이 행을 실행하면, 주문 테이블에 제품명이 나타나지 않는 것을 알 수 있다.
SELECT 주문.*, 제품.제품명 FROM 제품, 주문 WHERE 주문.주문제품=제품.제품번호;
SELECT 주문.주문번호, 주문.주문고객, 주문.주문제품, 제품.제품명, 주문.수량, 주문.배송지, 주문.주문일자 FROM 제품, 주문 WHERE 주문.주문제품=제품.제품번호;

-- apple 고객이 주문한 제품의 이름을 검색하시오.
